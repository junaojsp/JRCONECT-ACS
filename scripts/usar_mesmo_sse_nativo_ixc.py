#!/usr/bin/env python3
"""Use the same IXC SSE event stream semantics (event: trafego, data: {rx,tx}) through a transparent ACS proxy."""
import argparse, datetime, difflib, fcntl, hashlib, json, os, re, shutil, stat, subprocess, sys, tempfile
from pathlib import Path

VERSION='JRC_IXC_NATIVE_SSE_PROXY_V1'
JS_REL='assets/js/device-control-fix.js'
API_REL='api/stream-ixc-live-traffic.php'

API=r'''<?php
declare(strict_types=1);

require_once __DIR__ . '/../config/config.php';
require_once __DIR__ . '/../lib/IXCConfig.php';

if (function_exists('requireLogin')) requireLogin();
if (session_status() === PHP_SESSION_ACTIVE) session_write_close();

header('Content-Type: text/event-stream; charset=utf-8');
header('Cache-Control: no-cache, no-store, must-revalidate');
header('X-Accel-Buffering: no');
header('Connection: keep-alive');

@ini_set('output_buffering', '0');
@ini_set('zlib.output_compression', '0');
@ini_set('implicit_flush', '1');
@set_time_limit(0);
ignore_user_abort(false);

function jrcNativeFlush(): void
{
    while (function_exists('ob_get_level') && ob_get_level() > 0) @ob_end_flush();
    @flush();
}

$loginId = trim((string)($_GET['login_id'] ?? ''));
if ($loginId === '' || !preg_match('/^\d+$/', $loginId)) {
    http_response_code(400);
    echo "event: error\n";
    echo 'data: {"success":false,"message":"login_id IXC invalido"}' . "\n\n";
    jrcNativeFlush();
    exit;
}

try {
    $cfg = getIxcConfig();
    $url = rtrim((string)$cfg['base_url'], '/') .
        '/aplicativo/radusuarios/rel_22021.php?trafego=' . rawurlencode($loginId);
    $token = (string)$cfg['token'];

    // Browser reconnection hint. The upstream IXC stream itself is copied
    // verbatim after this line.
    echo "retry: 1500\n";
    echo ": JRC native IXC SSE proxy\n\n";
    jrcNativeFlush();

    $ch = curl_init($url);
    if ($ch === false) throw new RuntimeException('curl_init_failed');

    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => false,
        CURLOPT_FOLLOWLOCATION => false,
        CURLOPT_CONNECTTIMEOUT => 5,
        CURLOPT_TIMEOUT => 0,
        CURLOPT_HTTPHEADER => [
            'Accept: text/event-stream',
            'Cache-Control: no-cache',
            'ixcsoft: listar',
            'Authorization: Basic ' . base64_encode($token),
            'X-Requested-With: XMLHttpRequest',
        ],
        CURLOPT_WRITEFUNCTION => static function($ch, string $chunk): int {
            // Important: do not parse, rename or rebuild IXC events.
            // The browser receives exactly event: trafego / data: {rx,tx}
            // as generated by the IXC endpoint.
            echo $chunk;
            jrcNativeFlush();
            return connection_aborted() ? 0 : strlen($chunk);
        },
        CURLOPT_NOPROGRESS => false,
        CURLOPT_XFERINFOFUNCTION => static function(): int {
            return connection_aborted() ? 1 : 0;
        },
    ]);

    if (defined('CURLOPT_TCP_KEEPALIVE')) curl_setopt($ch, CURLOPT_TCP_KEEPALIVE, 1);
    if (defined('CURLOPT_TCP_KEEPIDLE')) curl_setopt($ch, CURLOPT_TCP_KEEPIDLE, 30);
    if (defined('CURLOPT_TCP_KEEPINTVL')) curl_setopt($ch, CURLOPT_TCP_KEEPINTVL, 15);

    curl_exec($ch);
    curl_close($ch);
} catch (Throwable $e) {
    if (!connection_aborted()) {
        echo "event: error\n";
        echo 'data: {"success":false,"message":"stream IXC indisponivel"}' . "\n\n";
        jrcNativeFlush();
    }
}
'''

def sha(data): return hashlib.sha256(data).hexdigest()

def patch_js(before):
    text=before.decode('utf-8')
    nl='\r\n' if '\r\n' in text else '\n'
    text=text.replace('\r\n','\n')
    if VERSION in text: return None
    if 'function jrcStartIxcSse' not in text or 'function jrcPaintIxcSseSample' not in text:
        raise RuntimeError('SSE IXC do navegador nao localizado.')

    # Replace only the custom JRC "traffic" event listener by the native IXC
    # "trafego" event listener. Keep the current chart/rendering logic.
    pattern=re.compile(
        r"""        source\.addEventListener\('traffic', event => \{\n"""
        r"""(?:.*?\n)*?"""
        r"""        \}\);""",
        re.M
    )
    matches=list(pattern.finditer(text))
    if len(matches)!=1:
        raise RuntimeError(f'Listener traffic esperado 1x, encontrado {len(matches)}x.')

    native="""        /* JRC_IXC_NATIVE_SSE_PROXY_V1 */
        source.addEventListener('trafego', event => {
            if (traffic.ixcSse !== source) return;
            let raw;
            try { raw = JSON.parse(event.data); } catch (_) { return; }

            const rxBps = Number(raw?.rx);
            const txBps = Number(raw?.tx);
            if (!Number.isFinite(rxBps) || !Number.isFinite(txBps) || rxBps < 0 || txBps < 0) return;

            jrcPaintIxcSseSample({
                download_mbps: rxBps / 1000000,
                upload_mbps: txBps / 1000000,
                sample_time: new Date().toISOString(),
                transport: 'ixc-native-sse'
            });
        });"""

    text=text[:matches[0].start()]+native+text[matches[0].end():]

    # Status wording only: native stream is now the exact IXC event source.
    text=text.replace(
        "setMonitorText('bandwidth-sample-status', 'IXC AO VIVO • stream conectado');",
        "setMonitorText('bandwidth-sample-status', 'IXC AO VIVO • conexao nativa');"
    )

    return text.replace('\n',nl).encode('utf-8')

def check_js(data):
    node=shutil.which('node')
    if not node: raise RuntimeError('Node.js ausente.')
    with tempfile.NamedTemporaryFile(suffix='.js') as f:
        f.write(data); f.flush()
        r=subprocess.run([node,'--check',f.name],capture_output=True,text=True)
    if r.returncode: raise RuntimeError('Sintaxe JS invalida: '+r.stderr[:1200])

def check_php(data):
    php=shutil.which('php')
    if not php: raise RuntimeError('PHP CLI ausente.')
    with tempfile.NamedTemporaryFile(suffix='.php') as f:
        f.write(data); f.flush()
        r=subprocess.run([php,'-l',f.name],capture_output=True,text=True)
    if r.returncode: raise RuntimeError('Sintaxe PHP invalida: '+(r.stderr or r.stdout)[:1200])

def atomic(path,data,meta=None):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd,name=tempfile.mkstemp(prefix='.jrc-native-sse-',dir=str(path.parent))
    try:
        with os.fdopen(fd,'wb') as out:
            out.write(data); out.flush(); os.fsync(out.fileno())
            if meta:
                os.fchmod(out.fileno(),stat.S_IMODE(meta.st_mode))
                if os.geteuid()==0: os.fchown(out.fileno(),meta.st_uid,meta.st_gid)
            else:
                os.fchmod(out.fileno(),0o644)
        os.replace(name,path)
    finally:
        if os.path.exists(name): os.unlink(name)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',default='/var/www/gacs')
    p.add_argument('--backup-dir',default='/root')
    m=p.add_mutually_exclusive_group()
    m.add_argument('--dry-run',action='store_true')
    m.add_argument('--rollback',type=Path)
    a=p.parse_args()
    parent=a.rollback.resolve().parent if a.rollback else Path(a.backup_dir).resolve()

    with (parent/'.jrc-native-ixc-sse.lock').open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)

        if a.rollback:
            b=a.rollback.resolve()
            meta=json.loads((b/'manifest.json').read_text())
            if meta.get('version')!=VERSION: raise RuntimeError('Backup incompativel.')
            root=Path(meta['root']); js=root/JS_REL; api=root/API_REL
            if sha(js.read_bytes())!=meta['js_after'] or sha(api.read_bytes())!=meta['api_after']:
                raise RuntimeError('Arquivos mudaram depois da instalacao; rollback cancelado.')
            js_old=(b/'device-control-fix.js').read_bytes()
            api_old=(b/'stream-ixc-live-traffic.php').read_bytes()
            check_js(js_old); check_php(api_old)
            atomic(js,js_old,js.stat()); atomic(api,api_old,api.stat())
            print('RESTAURADO: proxy SSE anterior.')
            return

        root=Path(a.root).resolve(); js=root/JS_REL; api=root/API_REL
        if not js.is_file() or js.is_symlink(): raise RuntimeError('device-control-fix.js nao encontrado.')
        if not api.is_file() or api.is_symlink(): raise RuntimeError('endpoint SSE nao encontrado.')

        js_before=js.read_bytes(); api_before=api.read_bytes()
        js_after=patch_js(js_before)
        if js_after is None:
            print('JA INSTALADO: SSE nativo IXC.')
            return
        api_after=API.encode('utf-8')
        check_js(js_before); check_js(js_after); check_php(api_before); check_php(api_after)

        print('VALIDADO: ACS retransmitira o mesmo event: trafego / data: {rx,tx} do IXC.')
        print('Nenhum token IXC sera exposto ao navegador.')
        if a.dry_run:
            print('SIMULACAO OK: nenhum arquivo alterado.')
            return

        if js.read_bytes()!=js_before or api.read_bytes()!=api_before:
            raise RuntimeError('Edicao concorrente detectada.')

        backup=Path(tempfile.mkdtemp(
            prefix='gacs-native-ixc-sse-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S')+'-',
            dir=str(parent)
        ))
        os.chmod(backup,0o700)
        shutil.copy2(js,backup/'device-control-fix.js')
        shutil.copy2(api,backup/'stream-ixc-live-traffic.php')
        shutil.copy2(Path(__file__).resolve(),backup/'install.py')

        meta={
            'version':VERSION,'root':str(root),
            'js_before':sha(js_before),'js_after':sha(js_after),
            'api_before':sha(api_before),'api_after':sha(api_after)
        }
        (backup/'manifest.json').write_text(json.dumps(meta,indent=2))
        (backup/'js.diff').write_text(''.join(difflib.unified_diff(
            js_before.decode().splitlines(True),js_after.decode().splitlines(True),
            fromfile=JS_REL,tofile=JS_REL)))
        (backup/'api.diff').write_text(''.join(difflib.unified_diff(
            api_before.decode().splitlines(True),api_after.decode().splitlines(True),
            fromfile=API_REL,tofile=API_REL)))

        atomic(api,api_after,api.stat())
        atomic(js,js_after,js.stat())

        ptr=parent/'gacs-native-ixc-sse-ultimo'
        ptr.write_text(str(backup)+'\n'); os.chmod(ptr,0o600)

        print('INSTALADO: mesma origem SSE e mesmos eventos de trafego usados pelo IXC.')
        print('Layout, grafico e media de 1s preservados.')
        print('Backup: '+str(backup))

if __name__=='__main__':
    try: main()
    except Exception as e:
        print('CANCELADO: '+str(e),file=sys.stderr)
        sys.exit(1)
